/**
 * Daily Attendance QR — generation, validation, and email distribution.
 *
 * Token strategy: opaque UUID stored in daily_attendance_qr with an expires_at
 * timestamp.  The DB record IS the source of truth; scanning checks the token
 * exists and that expires_at has not passed.  No HMAC required because the token
 * is never reconstructable from public inputs (unlike event registration QRs that
 * embed the registration code).
 *
 * QR content URL: ${APP_URL}/scan?token=${uuid}&src=daily
 *   — `src=daily` tells the scan page to show the correct expired-QR message.
 */

import { getSupabaseServer } from "@/lib/supabase-server";
import { sendSingleEmail }   from "@/lib/email-service";
import type { EmailAttachment } from "@/lib/email-service";
import QRCode from "qrcode";
import { getISTNow } from "@/lib/date-utils";
import { APP_URL }   from "@/lib/config";

// ── Helpers ───────────────────────────────────────────────────────────────────

function nowIST(): Date {
  return getISTNow();
}

function todayIST(): string {
  return nowIST().toISOString().slice(0, 10);
}

function fmtDateIST(iso: string): string {
  return new Date(iso).toLocaleDateString("en-IN", {
    timeZone:    "Asia/Kolkata",
    weekday:     "long",
    day:         "numeric",
    month:       "long",
    year:        "numeric",
  });
}

function fmtTimeIST(iso: string): string {
  return new Date(iso).toLocaleTimeString("en-IN", {
    timeZone: "Asia/Kolkata",
    hour:     "2-digit",
    minute:   "2-digit",
    hour12:   true,
  });
}

// ── Types ─────────────────────────────────────────────────────────────────────

export interface GeneratedQR {
  qrId:       string;
  token:      string;
  expiresAt:  string;   // ISO
  qrDataUrl:  string;   // data:image/png;base64,…
  qrBase64:   string;   // raw base64 PNG
  date:       string;   // YYYY-MM-DD
}

export interface ValidateResult {
  valid:       boolean;
  expired?:    boolean;
  qrId?:       string;
  locationId?: string | null;
  expiresAt?:  string;
}

export interface DistributeResult {
  sent:   number;
  failed: number;
}

// ── Generate ──────────────────────────────────────────────────────────────────

export async function generateDailyAttendanceQR(opts: {
  locationId?:     string | null;
  generatedBy?:    string;
  validityMinutes?: number;
  forDate?:        string;   // YYYY-MM-DD, defaults to today IST
}): Promise<GeneratedQR> {
  const db              = getSupabaseServer();
  const date            = opts.forDate ?? todayIST();
  const validityMinutes = opts.validityMinutes ?? 180;
  const generatedBy     = opts.generatedBy     ?? "system";
  const locationId      = opts.locationId       ?? null;

  const expiresAt = new Date(Date.now() + validityMinutes * 60 * 1000).toISOString();

  // Deactivate any previous QR for the same (date, location) slot
  await db
    .from("daily_attendance_qr")
    .update({ is_active: false })
    .eq("date", date)
    .is("location_id", locationId);

  // Insert new record — token is auto-generated by the DB default (gen_random_uuid())
  const { data: row, error } = await db
    .from("daily_attendance_qr")
    .insert({
      date,
      location_id:  locationId,
      expires_at:   expiresAt,
      generated_by: generatedBy,
      is_active:    true,
    })
    .select("id, token, expires_at, date")
    .single();

  if (error || !row) throw new Error(`QR insert failed: ${error?.message}`);

  const scanUrl  = `${APP_URL}/scan?token=${row.token}&src=daily`;
  const buffer   = await QRCode.toBuffer(scanUrl, { width: 400, margin: 2, errorCorrectionLevel: "H" });
  const base64   = buffer.toString("base64");
  const dataUrl  = `data:image/png;base64,${base64}`;

  return {
    qrId:      row.id,
    token:     row.token,
    expiresAt: row.expires_at,
    qrDataUrl: dataUrl,
    qrBase64:  base64,
    date:      row.date,
  };
}

// ── Validate ──────────────────────────────────────────────────────────────────

export async function validateDailyAttendanceQR(token: string): Promise<ValidateResult | null> {
  const db = getSupabaseServer();

  const { data } = await db
    .from("daily_attendance_qr")
    .select("id, expires_at, is_active, location_id")
    .eq("token", token)
    .maybeSingle();

  if (!data) return null;

  const expired = new Date(data.expires_at) < new Date();
  return {
    valid:      data.is_active && !expired,
    expired,
    qrId:       data.id,
    locationId: data.location_id,
    expiresAt:  data.expires_at,
  };
}

