// ── Send emails to all active recipients ──────────────────────────────────────

export async function sendDailyQREmails(opts: {
  qrId:        string;
  qrBase64:    string;
  date:        string;
  generatedAt: string;
  expiresAt:   string;
  locationId?: string | null;
}): Promise<DistributeResult> {
  const { qrId, qrBase64, date, generatedAt, expiresAt, locationId } = opts;
  const db = getSupabaseServer();

  // Fetch active recipients (matching location or receiving all)
  const { data: recipients } = await db
    .from("attendance_qr_recipients")
    .select("id, name, email, location_ids")
    .eq("is_active", true);

  if (!recipients?.length) return { sent: 0, failed: 0 };

  // Filter by location
  const targets = recipients.filter(r => {
    if (!r.location_ids || r.location_ids.length === 0) return true;  // receives all
    if (!locationId) return true;                                       // global QR → all
    return r.location_ids.includes(locationId);
  });

  // Resolve location name
  let locationName: string | undefined;
  if (locationId) {
    const { data: loc } = await db
      .from("training_locations")
      .select("name")
      .eq("id", locationId)
      .maybeSingle();
    locationName = loc?.name;
  }

  const html = buildQREmailHTML({ date, generatedAt, expiresAt, locationName });
  const displayDate = fmtDateIST(date + "T00:00:00");

  // QR image is served via a public URL (/api/qr-image/[date]) embedded in the HTML.
  // Gmail and most email clients render external HTTPS images without issues.
  // The attachment is a downloadable fallback for clients that block remote images.
  const attachment: EmailAttachment = {
    content:   qrBase64,
    mime_type: "image/png",
    name:      `attendance-qr-${date}.png`,
  };

  let sent = 0;
  let failed = 0;

  for (const r of targets) {
    // Pre-insert distribution log as 'pending'
    const { data: logRow } = await db
      .from("daily_qr_distribution_log")
      .insert({
        qr_id:           qrId,
        recipient_email: r.email,
        recipient_name:  r.name,
        status:          "pending",
      })
      .select("id")
      .single();

    try {
      const result = await sendSingleEmail({
        to:          r.email,
        subject:     `Attendance QR — ${displayDate}${locationName ? ` (${locationName})` : ""}`,
        html,
        attachments: [attachment],
      });

      if (result.ok) {
        sent++;
        if (logRow) {
          await db.from("daily_qr_distribution_log")
            .update({ status: "sent" })
            .eq("id", logRow.id);
        }
      } else {
        failed++;
        if (logRow) {
          await db.from("daily_qr_distribution_log")
            .update({ status: "failed", error_message: result.error ?? "Unknown error" })
            .eq("id", logRow.id);
        }
      }
    } catch (err) {
      failed++;
      if (logRow) {
        await db.from("daily_qr_distribution_log")
          .update({ status: "failed", error_message: String(err) })
          .eq("id", logRow.id);
      }
    }
  }

  return { sent, failed };
}

// ── Fetch active settings for a location (falls back to global) ───────────────

export async function getQRSettings(locationId?: string | null) {
  const db = getSupabaseServer();

  // Try location-specific first
  if (locationId) {
    const { data: locSettings } = await db
      .from("attendance_qr_settings")
      .select("*")
      .eq("location_id", locationId)
      .maybeSingle();
    if (locSettings) return locSettings;
  }

  // Fall back to global
  const { data: global } = await db
    .from("attendance_qr_settings")
    .select("*")
    .is("location_id", null)
    .maybeSingle();

  return global ?? {
    generation_time:       "05:00",
    validity_minutes:      180,
    auto_generate_enabled: true,
    auto_email_enabled:    true,
  };
}

// ── Execution log ─────────────────────────────────────────────────────────────
// Tracks every automated + manual run in attendance_qr_cron_log.
// The admin health dashboard reads this table. Failures here are NON-FATAL —
// if the log write fails, the caller's operation is not affected.

export type RunLogStatus = "running" | "success" | "partial" | "failed" | "skipped";

export async function createRunLog(opts: {
  executionDate: string;
  triggeredBy:   "cron" | "manual";
}): Promise<string | null> {
  const db = getSupabaseServer();
  const { data, error } = await db
    .from("attendance_qr_cron_log")
    .insert({
      execution_date: opts.executionDate,
      triggered_by:   opts.triggeredBy,
      status:         "running",
    })
    .select("id")
    .single();

  if (error) {
    console.error("[cron-log] createRunLog failed:", error.message);
    return null;
  }
  return data?.id ?? null;
}

export async function updateRunLog(
  logId: string | null,
  opts: {
    status:        RunLogStatus;
    qrId?:         string | null;
    emailsSent?:   number;
    emailsFailed?: number;
    errorMessage?: string;
    details?:      Record<string, unknown>;
  },
): Promise<void> {
  if (!logId) return;
  const db = getSupabaseServer();

  const { error } = await db
    .from("attendance_qr_cron_log")
    .update({
      finished_at:    new Date().toISOString(),
      status:         opts.status,
      qr_id:          opts.qrId ?? null,
      emails_sent:    opts.emailsSent    ?? 0,
      emails_failed:  opts.emailsFailed  ?? 0,
      error_message:  opts.errorMessage  ?? null,
      details:        opts.details       ?? null,
    })
    .eq("id", logId);

  if (error) {
    console.error("[cron-log] updateRunLog failed:", error.message);
  }
}

// ── Failure alert ──────────────────────────────────────────────────────────────
